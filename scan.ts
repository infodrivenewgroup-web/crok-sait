function mix(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function buildScanLog(runId: number): Array<{ at: number; text: string }> {
  const rand = mix((runId ^ 0x6a09e667) >>> 0);
  return LOG_SLOTS.map((slot) => ({
    at: slot.at,
    text: slot.options[Math.floor(rand() * slot.options.length)] ?? slot.options[0],
  }));
}


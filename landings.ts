const bySlug = new Map(LANDINGS.map((page) => [page.slug, page]));

export function landingBySlug(slug: string): LandingPage | null {
  return bySlug.get(slug) ?? null;
}

export function relatedLandings(slug: string, count = 4): LandingPage[] {
  const index = LANDINGS.findIndex((page) => page.slug === slug);
  if (index < 0) return [];
  const related: LandingPage[] = [];
  for (let step = 1; related.length < count && step < LANDINGS.length; step += 1) {
    related.push(LANDINGS[(index + step) % LANDINGS.length]);
  }
  return related;
}

function setMeta(attr: "name" | "property", key: string, content: string) {
  let node = document.head.querySelector(`meta[${attr}="${key}"]`);
  if (!node) {
    node = document.createElement("meta");
    node.setAttribute(attr, key);
    document.head.appendChild(node);
  }
  node.setAttribute("content", content);
}

export function syncLandingMeta(page: LandingPage, showOffer: boolean) {
  const origin = window.location.origin;
  const url = `${origin}/${page.slug}`;
  const image = `${origin}/og.jpg`;
  if (showOffer) document.title = page.title;
  setMeta("name", "description", page.description);
  setMeta("property", "og:title", showOffer ? page.title : document.title);
  setMeta("property", "og:description", page.description);
  setMeta("property", "og:url", url);
  setMeta("property", "og:image", image);
  setMeta("property", "og:image:alt", page.title);
  setMeta("name", "twitter:title", showOffer ? page.title : document.title);
  setMeta("name", "twitter:description", page.description);
  setMeta("name", "twitter:image", image);
  setMeta("name", "twitter:url", url);
  const canonicals = document.head.querySelectorAll('link[rel="canonical"]');
  const canonical = canonicals[0] ?? document.createElement("link");
  if (!canonicals.length) {
    canonical.setAttribute("rel", "canonical");
    document.head.appendChild(canonical);
  }
  canonical.setAttribute("href", url);
  for (let i = 1; i < canonicals.length; i += 1) canonicals[i].remove();
}


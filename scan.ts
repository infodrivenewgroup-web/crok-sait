export type ServiceState = "idle" | "active" | "done";

export function stageIndexAt(elapsed: number): number {
  let index = 0;
  for (let i = 0; i < STAGE_AT.length; i += 1) {
    if (elapsed >= STAGE_AT[i]) index = i;
  }
  return index;
}

export function stageProgress(elapsed: number): number {
  const index = stageIndexAt(elapsed);
  const start = STAGE_AT[index];
  const end = STAGE_AT[index + 1] ?? SCAN_MS;
  return Math.min(1, Math.max(0, (elapsed - start) / (end - start)));
}

export function browserClock(ms: number): string {
  const date = new Date(ms);
  const part = (value: number) => String(value).padStart(2, "0");
  return `${part(date.getHours())}:${part(date.getMinutes())}:${part(date.getSeconds())}`;
}

export function serviceState(id: string, elapsed: number): ServiceState {
  const indexes = STAGES.map((stage, index) => (stage.service === id ? index : -1)).filter((index) => index >= 0);
  const current = elapsed >= SCAN_MS ? STAGES.length : stageIndexAt(elapsed);
  if (indexes.some((index) => index === current && elapsed < SCAN_MS)) return "active";
  if (indexes.every((index) => index < current)) return "done";
  return "idle";
}

export function formatClock(ms: number): string {
  const total = Math.max(0, Math.ceil(ms / 1000));
  const m = Math.floor(total / 60);
  const s = total % 60;
  return `${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}`;
}

